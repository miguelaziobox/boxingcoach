function getCurrentLang() {
  if (typeof window !== 'undefined' && window.BoxingStorage) {
    return window.BoxingStorage.getStore().lang || 'en';
  }
  return localStorage.getItem('lang') || 'en';
}

function T(txt) {
  if (!txt) return '';
  if (getCurrentLang() === 'en') return txt;
  return PT_DICT[txt] || txt;
}

function applyTranslations(root) {
  const el = root || document.body;
  if (!el) return;
  const targets = el.querySelectorAll('[data-i18n]');
  targets.forEach(node => {
    const key = node.getAttribute('data-i18n');
    if (key) node.textContent = T(key);
  });
  const phTargets = el.querySelectorAll('[data-i18n-placeholder]');
  phTargets.forEach(node => {
    const key = node.getAttribute('data-i18n-placeholder');
    if (key) node.setAttribute('placeholder', T(key));
  });
}
